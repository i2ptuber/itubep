"""
origin_validation.py — единая проверка формата Origin, допустимого для
сопряжения с мостом и для последующих "обратных" запросов моста на сайт.

КРИТИЧНО: это не просто гигиена формата. Без этой проверки мост соглашался
сопрягаться с ЛЮБЫМ Origin, включая clearnet-домены — а
snark/publisher.py:_requests_session_for посылает HTTP-запросы напрямую,
БЕЗ I2P-прокси, для любого хоста, не оканчивающегося на ".i2p". Комбинация
этих двух фактов означала, что мост мог быть обманут на сопряжение с
clearnet-сайтом и после этого слал бы reactions/comments/studio-обновления
и даже манифест публикации видео напрямую на реальный IP этого сайта,
раскрывая настоящий IP-адрес пользователя — то есть деанонимизируя его.
Эта проверка — обязательный барьер ДО показа диалога сопряжения, а не
только красивое сообщение об ошибке.
"""

from __future__ import annotations

import re
from urllib.parse import urlparse

# I2P b32-адрес: 52 символа base32 (RFC4648 без паддинга, нижний регистр)
# + ".b32.i2p". Это формат постоянного адреса, который выдаёт сам
# I2P-роутер для eepsite и который физически не подделать без владения
# destination-ключом.
_B32_I2P_RE = re.compile(r"^[a-z2-7]{52}\.b32\.i2p$")

# "Дружественное" i2p-имя (заведённое через адресную книгу/hosts.txt,
# подписки на jump-сервисы и т.п., напр. "itubep.i2p") — САМЫЙ обычный
# способ адресации eepsite для человека, b32 используется в основном как
# запасной канонический адрес. В отличие от b32 такое имя — не
# криптографический адрес сам по себе (его можно попытаться захватить в
# чужой адресной книге), но оно физически НЕ МОЖЕТ разрешиться в
# clearnet-хост: любой Origin с этим суффиксом браузер получил только
# оттого, что сам обратился к хосту через I2P (роутер резолвит .i2p-имена
# только в I2P destination'ы, не в обычный DNS/IP) — то есть тот же самый
# инвариант "запрос не покидал I2P", ради которого вообще существует эта
# проверка, здесь тоже выполняется. Обычные доменные метки (буквы/цифры/
# дефис, точки как разделители), последняя метка — буквально "i2p".
_FRIENDLY_I2P_RE = re.compile(
    r"^(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+i2p$"
)

# Разрешаем localhost/127.0.0.1 ТОЛЬКО для локальной разработки (например,
# сайт поднят на том же хосте без реального I2P-роутера) — такие запросы в
# любом случае никогда не покидают машину пользователя, поэтому не несут
# риска деанонимизации, в отличие от произвольного внешнего хоста.
_DEV_HOSTS = {"localhost", "127.0.0.1", "[::1]"}


def is_valid_pairing_origin(origin: str) -> bool:
    """
    True, только если Origin — это реальный I2P-адрес (b32 ИЛИ
    "дружественное" .i2p-имя, http:// или https://) либо явный
    localhost-адрес для разработки. Всё остальное (произвольные
    clearnet-домены, IP-адреса, .onion и т.п.) отклоняется — мост не
    должен даже показывать GUI-диалог сопряжения для такого Origin.

    ВАЖНО: критерий здесь намеренно совпадает с is_i2p_host() ниже (тот же
    смысл "запрос идёт внутри I2P" в обе стороны — и на входе при
    сопряжении/CORS, и на выходе при решении, обязателен ли I2P-прокси).
    Раньше эта проверка признавала только b32-адреса, что отклоняло
    (вместе с CORS для /bridge/*) совершенно легитимные eepsite на
    "дружественных" .i2p-именах вроде "itubep.i2p" — сопряжение, плеер,
    лайки и комментарии одинаково переставали работать, хотя сам сайт был
    настоящим I2P-сайтом.
    """
    if not origin:
        return False
    try:
        parsed = urlparse(origin)
    except ValueError:
        return False

    if parsed.scheme not in ("http", "https"):
        return False

    host = (parsed.hostname or "").lower()
    if host in _DEV_HOSTS:
        return True

    return bool(_B32_I2P_RE.match(host) or _FRIENDLY_I2P_RE.match(host))


def is_i2p_host(hostname: str) -> bool:
    """Используется на стороне снаряжения запросов (publisher.py), чтобы
    решить, обязателен ли I2P-прокси."""
    return (hostname or "").lower().endswith(".i2p")
